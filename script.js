let observer;
function observeReveals(){
  if(!observer){
    observer=new IntersectionObserver(entries=>entries.forEach(e=>{
      if(e.isIntersecting){e.target.classList.add("in");observer.unobserve(e.target)}
    }),{threshold:.1});
  }
  qsa(".reveal:not(.in)").forEach(el=>observer.observe(el));
}

function renderDynamic(){
  const data=CONTENT[lang];
  const labPreview=qs("#labPreview"), labGrid=qs("#labGrid");
  const signalsPreview=qs("#signalsPreview"), signalsGrid=qs("#signalsGrid");
  if(labPreview) labPreview.innerHTML=data.lab.slice(0,2).map(labCard).join("");
  if(labGrid) labGrid.innerHTML=data.lab.map(labCard).join("");
  if(signalsPreview) signalsPreview.innerHTML=data.signals.slice(0,3).map(x=>signalCard(x,true)).join("");
  if(signalsGrid) signalsGrid.innerHTML=data.signals.map(x=>signalCard(x,false)).join("");
  observeReveals();
}

