let observer;
function observeReveals(){
  if(!observer) observer=new IntersectionObserver(entries=>entries.forEach(e=>{
    if(e.isIntersecting){
      e.target.classList.add("in");
      observer.unobserve(e.target);
    }
  }),{threshold:.08});
  qsa(".reveal:not(.in)").forEach(el=>observer.observe(el));
}

