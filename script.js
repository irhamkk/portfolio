// Snappy, Modern Magnetic Custom Cursor (Zero Lag)
const finePointer=matchMedia("(pointer:fine)").matches,reduceMotion=matchMedia("(prefers-reduced-motion: reduce)").matches;
if(finePointer&&!reduceMotion){
  document.body.classList.add("cursor-ready");
  const canvas=document.createElement("canvas");canvas.id="cursor-brush";document.body.appendChild(canvas);
  const dot=document.createElement("div");dot.className="cursor-dot";
  const ring=document.createElement("div");ring.className="cursor-ring";document.body.append(dot,ring);
  const ctx=canvas.getContext("2d");
  let dpr,w,h,mx=innerWidth/2,my=innerHeight/2,rx=mx,ry=my,lx=mx,ly=my,n=0;
  const trail=[];

  function resize(){
    w=innerWidth;h=innerHeight;
    dpr=Math.min(devicePixelRatio||1,2);
    canvas.width=Math.round(w*dpr);canvas.height=Math.round(h*dpr);
    canvas.style.width=w+"px";canvas.style.height=h+"px";
    ctx.setTransform(dpr,0,0,dpr,0,0);
  }
  resize();addEventListener("resize",resize,{passive:true});

  addEventListener("mousemove",e=>{
    mx=e.clientX;my=e.clientY;
    dot.style.transform=`translate3d(${mx}px, ${my}px, 0)`;

    const dx=mx-lx,dy=my-ly,dist=Math.hypot(dx,dy);
    if(dist>4){
      n++;
      trail.push({
        x:mx,y:my,px:lx,py:ly,
        life:1,
        width:Math.min(9, 3.5 + dist * 0.08),
        color:n%4===0?"232,196,61":"109,138,34"
      });
      if(trail.length>20) trail.splice(0, trail.length-20);
      lx=mx;ly=my;
    }
  },{passive:true});

  const interactive="a,button,textarea,select,.home-row,.lab-card,.signal-stream-card,.signal-feature,.home-signal-mini";
  document.addEventListener("mouseover",e=>{
    if(e.target.closest(interactive)){
      ring.classList.add("is-hover");
    }
  });
  document.addEventListener("mouseout",e=>{
    if(e.target.closest(interactive)){
      ring.classList.remove("is-hover");
    }
  });
  document.addEventListener("mousedown",()=>{
    ring.classList.add("is-down");
  });
  document.addEventListener("mouseup",()=>{
    ring.classList.remove("is-down");
  });

  // Snappy 0.38 lerp (no drag / no lag)
  (function animate(){
    rx += (mx - rx) * 0.38;
    ry += (my - ry) * 0.38;
    ring.style.transform = `translate3d(${rx}px, ${ry}px, 0)`;

    ctx.clearRect(0,0,w,h);
    ctx.lineCap="round";ctx.lineJoin="round";
    for(let i=trail.length-1;i>=0;i--){
      const p=trail[i];
      p.life -= 0.06;
      if(p.life<=0){trail.splice(i,1);continue}
      const a=Math.max(0,p.life)*0.16;
      ctx.strokeStyle=`rgba(${p.color},${a})`;
      ctx.lineWidth=p.width*p.life;
      ctx.beginPath();
      ctx.moveTo(p.px,p.py);
      ctx.quadraticCurveTo((p.px+p.x)/2,(p.py+p.y)/2,p.x,p.y);
      ctx.stroke();
    }
    requestAnimationFrame(animate);
  })();
}

