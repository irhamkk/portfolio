let selectedSignalIndex = 0;

function bindHomeSignalClicks(){
  const rail=qs("#homeSignalsSide");
  if(!rail) return;
  rail.onclick = (e) => {
    const item = e.target.closest(".home-signal-mini");
    if(!item) return;
    const idx = parseInt(item.dataset.signalIdx, 10);
    if(isNaN(idx)) return;
    selectedSignalIndex = idx;
    const data = CONTENT[lang];
    const targetSignal = data.signals[idx];
    if(!targetSignal) return;

    qsa(".home-signal-mini", rail).forEach(el => el.classList.toggle("is-active", el === item));
    const homeLead = qs("#homeSignalLead");
    if(homeLead){
      homeLead.style.opacity = "0";
      homeLead.style.transform = "translateY(6px)";
      setTimeout(() => {
        homeLead.innerHTML = signalFeature(targetSignal);
        homeLead.style.transition = "opacity 0.25s ease, transform 0.25s ease";
        homeLead.style.opacity = "1";
        homeLead.style.transform = "translateY(0)";
      }, 140);
    }
  };
}

function renderDynamic(){
  const data=CONTENT[lang];
  const homeLead=qs("#homeSignalLead");
  if(homeLead) {
    const curIdx = selectedSignalIndex < data.signals.length ? selectedSignalIndex : 0;
    homeLead.innerHTML=signalFeature(data.signals[curIdx]);
  }

  const homeSide=qs("#homeSignalsSide");
  if(homeSide) {
    // Show 3 latest signals in the rail
    homeSide.innerHTML=data.signals.slice(0,3).map(signalMini).join("");
    bindHomeSignalClicks();
  }

  const signalCount=String(data.signals.length).padStart(2,"0");
  const labCount=String(data.lab.length).padStart(2,"0");
  const homeSignalCount=qs("#homeSignalCount");
  const homeSignalsIndexCount=qs("#homeSignalsIndexCount");
  const homeLabCount=qs("#homeLabCount");
  if(homeSignalCount) homeSignalCount.textContent=signalCount;
  if(homeSignalsIndexCount) homeSignalsIndexCount.textContent=signalCount;
  if(homeLabCount) homeLabCount.textContent=labCount;

  const labTitle=qs("#homeLabFeatureTitle");
  const labCopy=qs("#homeLabFeatureCopy");
  if(labTitle) labTitle.textContent=data.lab[0].title;
  if(labCopy) labCopy.textContent=data.lab[0].copy;

  const homeLabList=qs("#homeLabList");
  if(homeLabList) homeLabList.innerHTML=data.lab.slice(0,3).map(homeLabRow).join("");

  const labGrid=qs("#labGrid");
  if(labGrid) labGrid.innerHTML=data.lab.map(labCard).join("");

  renderSignals();
  observeReveals();
}

